do $$
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'products'
      and column_name = 'id'
      and is_identity = 'YES'
  ) then
    alter table public.products alter column id add generated by default as identity;
  end if;
end
$$;

select setval(
  pg_get_serial_sequence('public.products', 'id'),
  coalesce((select max(id) from public.products), 0) + 1,
  false
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

grant select, insert, update, delete on public.products, public.product_images to authenticated;
revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;

do $$
declare
  identity_sequence text := pg_get_serial_sequence('public.products', 'id');
