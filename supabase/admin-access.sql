create or replace function public.admin_save_product(
  p_id integer,
  p_category text,
  p_name text,
  p_description text,
  p_price_pix_cents integer,
  p_price_card_cents integer,
  p_illustrative boolean,
  p_is_active boolean,
  p_image_urls text[]
)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  saved_id integer;
begin
  if exists (
    select 1
    from pg_catalog.unnest(coalesce(p_image_urls, array[]::text[])) as image(url)
    where image.url !~ '^https://'
  ) then
    raise exception 'Product image URLs must use HTTPS.';
  end if;

  if p_id is null then
    insert into public.products (
      category,
      name,
      description,
      price_pix_cents,
      price_card_cents,
      illustrative,
      is_active
    )
    values (
      p_category,
      p_name,
      p_description,
      p_price_pix_cents,
      p_price_card_cents,
      p_illustrative,
      p_is_active
    )
    returning id into saved_id;
  else
    update public.products
    set category = p_category,
        name = p_name,
        description = p_description,
        price_pix_cents = p_price_pix_cents,
        price_card_cents = p_price_card_cents,
        illustrative = p_illustrative,
        is_active = p_is_active
    where id = p_id
    returning id into saved_id;

    if saved_id is null then
      raise exception 'Product not found or not editable.';
    end if;
  end if;

  delete from public.product_images where product_id = saved_id;

  insert into public.product_images (product_id, position, url)
  select saved_id, (image.ordinality - 1)::integer, image.url
  from pg_catalog.unnest(coalesce(p_image_urls, array[]::text[]))
    with ordinality as image(url, ordinality);

  return saved_id;
end;
$$;

revoke all on function public.admin_save_product(integer, text, text, text, integer, integer, boolean, boolean, text[]) from public, anon;
grant execute on function public.admin_save_product(integer, text, text, text, integer, integer, boolean, boolean, text[]) to authenticated;
